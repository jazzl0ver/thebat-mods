param(
    [Parameter(Position = 0)]
    [string]$Path = ".\TheBat64.exe",

    [Parameter(Position = 1)]
    [string]$OutputPath
)

$ErrorActionPreference = "Stop"

# This patch is intentionally tied to the exact The Bat! 12 executable used
# to build it. It refuses to patch any other binary.
$ExpectedInputSha256  = "5ff1f4771fbbe0cec8091c67b90f752190feb2ce173136c9951006b38cc401b7"
$ExpectedOutputSha256 = "d4f430ce2b6077e0bbe3c595c7492c7b58971614a811e2c5e20f9d8e0fa8b324"

function Get-BytesSha256([byte[]]$Data) {
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        $hash = $sha.ComputeHash($Data)
        return ([BitConverter]::ToString($hash)).Replace("-", "").ToLowerInvariant()
    }
    finally {
        $sha.Dispose()
    }
}

$inputFile = [System.IO.Path]::GetFullPath($Path)
if (-not [System.IO.File]::Exists($inputFile)) {
    throw "Input file not found: $inputFile"
}

if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $dir  = [System.IO.Path]::GetDirectoryName($inputFile)
    $name = [System.IO.Path]::GetFileNameWithoutExtension($inputFile)
    $ext  = [System.IO.Path]::GetExtension($inputFile)
    $OutputPath = [System.IO.Path]::Combine($dir, $name + "_mod" + $ext)
}
$outputFile = [System.IO.Path]::GetFullPath($OutputPath)

$bytes = [System.IO.File]::ReadAllBytes($inputFile)
$inputHash = Get-BytesSha256 $bytes

if ($inputHash -eq $ExpectedOutputSha256) {
    Write-Host "This executable is already patched."
    if ($outputFile -ne $inputFile) {
        [System.IO.File]::WriteAllBytes($outputFile, $bytes)
        Write-Host "Copied to: $outputFile"
    }
    exit 0
}

if ($inputHash -ne $ExpectedInputSha256) {
    throw @"
Unsupported executable.
Expected SHA-256: $ExpectedInputSha256
Actual SHA-256:   $inputHash

This script uses exact offsets and resource bytes. Patching another build could corrupt it.
"@
}

