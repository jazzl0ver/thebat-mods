$packed = [Convert]::FromBase64String(($PatchBase64 -replace "\s", ""))
$packedStream = New-Object System.IO.MemoryStream(,$packed)
$gzip = New-Object System.IO.Compression.GZipStream(
    $packedStream,
    [System.IO.Compression.CompressionMode]::Decompress
)
$reader = New-Object System.IO.BinaryReader($gzip)

try {
    $magic = [System.Text.Encoding]::ASCII.GetString($reader.ReadBytes(4))
    if ($magic -ne "TBI1") { throw "Invalid embedded icon patch." }

    $count = $reader.ReadUInt32()
    for ($i = 0; $i -lt $count; $i++) {
        $offset = $reader.ReadUInt32()
        $length = $reader.ReadUInt32()
        $chunk = $reader.ReadBytes([int]$length)
        if ($chunk.Length -ne $length) { throw "Truncated embedded icon patch." }
        if (($offset + $length) -gt $bytes.Length) { throw "Icon patch range is outside the executable." }
        [Array]::Copy($chunk, 0, $bytes, [int]$offset, [int]$length)
    }
}
finally {
    $reader.Dispose()
    $gzip.Dispose()
    $packedStream.Dispose()
}

$outputHash = Get-BytesSha256 $bytes
if ($outputHash -ne $ExpectedOutputSha256) {
    throw "Verification failed. Produced SHA-256: $outputHash"
}

if ($outputFile -eq $inputFile) {
    $backup = $inputFile + ".bak"
    if (-not [System.IO.File]::Exists($backup)) {
        [System.IO.File]::Copy($inputFile, $backup, $false)
        Write-Host "Backup: $backup"
    }
}

[System.IO.File]::WriteAllBytes($outputFile, $bytes)
Write-Host "Patched successfully: $outputFile"
Write-Host "SHA-256: $outputHash"
